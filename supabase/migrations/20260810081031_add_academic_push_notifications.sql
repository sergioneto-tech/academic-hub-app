create extension if not exists pg_net;
create extension if not exists pg_cron;

create table if not exists public.push_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  deadlines_enabled boolean not null default true,
  exams_enabled boolean not null default true,
  uab_enabled boolean not null default true,
  efinal_lead_days integer not null default 2 check (efinal_lead_days between 1 and 14),
  exam_lead_days integer not null default 7 check (exam_lead_days between 1 and 30),
  uab_lead_days integer not null default 3 check (uab_lead_days between 1 and 30),
  timezone text not null default 'Europe/Lisbon',
  updated_at timestamptz not null default now()
);

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  device_label text,
  user_agent text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists push_subscriptions_user_idx
  on public.push_subscriptions (user_id)
  where enabled = true;

create table if not exists public.push_delivery_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_key text not null,
  sent_at timestamptz not null default now(),
  unique (user_id, event_key)
);

-- Configuração de servidor: sem privilégios para anon/authenticated.
-- Os valores sensíveis são inseridos diretamente em produção e nunca ficam no repositório.
create table if not exists public.push_server_config (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

alter table public.push_preferences enable row level security;
alter table public.push_preferences force row level security;
alter table public.push_subscriptions enable row level security;
alter table public.push_subscriptions force row level security;
alter table public.push_delivery_log enable row level security;
alter table public.push_delivery_log force row level security;
alter table public.push_server_config enable row level security;
alter table public.push_server_config force row level security;

