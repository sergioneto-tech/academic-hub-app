create or replace function public.touch_push_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
revoke execute on function public.touch_push_updated_at() from public, anon, authenticated;

drop trigger if exists touch_push_preferences_updated_at on public.push_preferences;
create trigger touch_push_preferences_updated_at
before update on public.push_preferences
for each row execute function public.touch_push_updated_at();

drop trigger if exists touch_push_subscriptions_updated_at on public.push_subscriptions;
create trigger touch_push_subscriptions_updated_at
before update on public.push_subscriptions
for each row execute function public.touch_push_updated_at();

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create or replace function private.dispatch_academic_push_notifications()
returns void
language plpgsql
security definer
set search_path = public, extensions, private
as $$
declare
  function_url text;
  cron_secret text;
begin
  select value into function_url from public.push_server_config where key = 'function_url';
  select value into cron_secret from public.push_server_config where key = 'cron_secret';
  if function_url is null or cron_secret is null then
    return;
  end if;

  perform net.http_post(
    url := function_url,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-secret', cron_secret
    ),
    body := '{"mode":"scheduled"}'::jsonb,
    timeout_milliseconds := 10000
  );
end;
$$;
revoke execute on function private.dispatch_academic_push_notifications() from public, anon, authenticated;
